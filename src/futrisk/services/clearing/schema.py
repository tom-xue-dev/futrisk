def schema_ddl(version: int = 1) -> str:
    """``render_ddl`` of the tables added by schema ``version`` (``schema_version`` excluded)."""
    wanted = V1_TABLES if version == 1 else V2_TABLES if version == 2 else frozenset()
    md = MetaData()
    for table in METADATA.sorted_tables:
        if table.name != "schema_version" and table.name in wanted:
            table.to_metadata(md)
    return render_ddl(md)


