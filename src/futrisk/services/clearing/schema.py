"""clearing.db schema and migrations (03 §4.4, §4.0, §9).

clearing.db belongs to the clearing-worker alone (03 §1, DB-01). Besides the
common tables (``schema_version``, ``db_meta``, ``outbox``/``outbox_topics``,
``processed_commands``, ``fact_cursors``) it holds:

* local copies: ``trades`` (only the ``Trade`` messages of ``td.exec.*``) and
  ``cash_movements`` (``risk.cash.*``), so that settlement never reads another
  service's database (01 §5.3.4);
* the saga: ``eod_runs`` keyed by ``(trading_day, version)`` (02 §8.4);
* prices: ``official_prices``, ``price_overrides`` (audit) and ``settlement_prices``;
* results: ``account_settlements``, ``position_settlements``, ``margin_groups``,
  ``trade_settlements``, ``close_details``, ``recon_checks``;
* next-day snapshots: ``sod_versions`` (with ``pushed_ns``) and ``sod_accounts`` /
  ``sod_lots`` / ``sod_prices``;
* ``reports`` (03 §5.3) and ``backtest_runs``;
* ``config_history`` (schema v2, internal): every committed config version the
  worker saw, with the trading day from which its settlement-relevant sections
  (``products.yaml`` and the calendar, 02 §7.10 ``NEXT_TRADING_DAY``) apply, so
  that a day is settled with the configuration in force on that day (01 §6.7).

The whole database runs with ``synchronous=FULL`` (03 DB-03). Money and prices
are canonical decimal strings (DB-06). Column names equal the 02 payload field
names (03 §3.2). Migrations are frozen SQL (03 §9, forward-only, checksummed):
:data:`V1_SQL` is :func:`futrisk.db.render_ddl` of :data:`METADATA` without
``schema_version`` (the migration runner creates that one itself); a unit test
keeps the two in sync. The SQL lives in this module rather than in a ``.sql``
data file so that a frozen executable needs no extra data files (same
convention as the other services).
Schema v2 (:data:`V2_SQL`) adds ``config_history``; :data:`V1_TABLES` keeps the
v1 table set so that the frozen v1 text can still be checked.
"""

