def _quoted_enum_col(name: str, values: type[StrEnum], **kw: Any) -> Column[Any]:
    """``ENUM`` column whose name is an SQL keyword (``check``): the CHECK must quote it."""
    quoted = ",".join(f"'{m.value}'" for m in values)
    return Column(name, Text, CheckConstraint(f'"{name}" IN ({quoted})'), **kw)


