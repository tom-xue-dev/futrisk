"""REST request bodies (02 §9.6); they appear in ``/openapi.json`` and ``/docs``.

Bodies map one-to-one to the bus payloads of 02 §6/§7 (the gateway adds the
idempotency key, ``actor`` and ``role``); money and exact prices are ``DecStr``
(02 §4.3: plain decimal strings, no exponent, no ``+``).
"""

from __future__ import annotations

import re
import uuid
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator

from futrisk.messages.enums import (
    CashType,
    ClockTarget,
    Direction,
    Offset,
    OrderSource,
    OrderType,
    ReconResolution,
    TimeInForce,
)

DECSTR = re.compile(r"^-?\d+(\.\d+)?$")
MONEY = re.compile(r"^\d+(\.\d{1,2})?$")


class _Body(BaseModel):
    model_config = ConfigDict(extra="forbid")


def _decstr(v: str) -> str:
    if not DECSTR.fullmatch(v):
        raise ValueError("must be a plain decimal string (DecStr, 02 §4.3)")
    return v


class OrderBody(_Body):
    """``POST /orders`` = ``OrderRequest`` (02 §7.4); ``client_order_id`` (a UUID, UUIDv7 recommended,
    generated by the client) is the idempotency key."""

    client_order_id: str = Field(min_length=1, max_length=64)

    @field_validator("client_order_id")
    @classmethod
    def _uuid(cls, v: str) -> str:
        try:
            uuid.UUID(v)
        except ValueError as exc:
            raise ValueError("client_order_id must be a UUID (UUIDv7 recommended, 02 §7.4)") from exc
        return v
    account_id: str
    instrument_id: str
    direction: Direction
    offset: Offset
    order_type: OrderType = OrderType.LIMIT
    tif: TimeInForce = TimeInForce.GFD
    price: float | None = None
    qty: int = Field(gt=0)
    source: OrderSource = OrderSource.MANUAL
    strategy_tag: str | None = None


class CancelAllBody(_Body):
    account_id: str
    scope: Literal["ALL", "OPEN_ONLY"] = "ALL"
    product: str | None = None
    reason: str = ""


class CancelBody(_Body):
    reason: str | None = None


class CashBody(_Body):
    """``POST /accounts/{id}/cash`` -> ``cash.move`` (the Idempotency-Key becomes ``movement_id``)."""

    type: CashType
    amount: str = Field(description="positive amount in yuan, at most 2 decimals, e.g. \"1000000.00\"")
    reason: str = Field(min_length=1)

    @field_validator("amount")
    @classmethod
    def _amount(cls, v: str) -> str:
        if not MONEY.fullmatch(v) or float(v) <= 0:
            raise ValueError("amount must be a positive DecStr with at most 2 decimals")
        return v


class ResetBody(_Body):
    reason: str = Field(min_length=1)
    rule_id: str | None = None
    level: str | None = None


class HaltBody(_Body):
    reason: str = Field(min_length=1)


class KillSwitchBody(_Body):
    on: bool
    reason: str = Field(min_length=1)


class AckBody(_Body):
    note: str | None = None


class ReconResolveBody(_Body):
    resolution: ReconResolution
    note: str = Field(min_length=1)


class LiquidationConfirmBody(_Body):
    decision: Literal["CONFIRM", "CANCEL"]


class ForceUnfreezeBody(_Body):
    reason: str = Field(min_length=1)


class SettleRunBody(_Body):
    td: str = Field(pattern=r"^\d{8}$")
    force_new_version: bool = False


class PriceOverrideBody(_Body):
    price: str
    reason: str = Field(min_length=1)

    @field_validator("price")
    @classmethod
    def _price(cls, v: str) -> str:
        return _decstr(v)


class OfficialPriceItem(_Body):
    instrument_id: str
    price: str

    @field_validator("price")
    @classmethod
    def _price(cls, v: str) -> str:
        return _decstr(v)


class OfficialPricesBody(_Body):
    prices: list[OfficialPriceItem] = Field(min_length=1)
    source: str = "manual"


class SeedSodBody(_Body):
    """``POST /settlement/seed-sod`` -> ``settle.seed_sod``; ``accounts`` items are ``SodAccount`` (02 §7.8)."""

    trading_day: str = Field(pattern=r"^\d{8}$")
    accounts: list[dict[str, Any]] = Field(min_length=1)
    pre_settle: dict[str, str] = Field(default_factory=dict)
    reason: str = Field(min_length=1)


class TradeImportBody(_Body):
    """``POST /trades/import`` -> ``td.import_trades``; ``trades`` items are ``Trade`` (02 §7.5)."""

    trading_day: str = Field(pattern=r"^\d{8}$")
    trades: list[dict[str, Any]] = Field(min_length=1)
    source: str = "import"


class BacktestBody(_Body):
    config_name: str = Field(min_length=1)
    overrides: dict[str, Any] | None = None


class SourceBody(_Body):
    action: Literal["EXCLUDE", "INCLUDE"]
    reason: str = Field(min_length=1)


class DemoFaultBody(_Body):
    type: str
    target: str | None = None
    params: dict[str, Any] = Field(default_factory=dict)
    duration_s: float | None = Field(default=None, ge=0)


class DemoShockBody(_Body):
    instruments: list[str] | None = None
    sector: str | None = None
    pct: float
    duration_s: float = Field(default=0.0, ge=0)
    shape: Literal["STEP", "LINEAR"] = "STEP"


class DemoScenarioBody(_Body):
    name: str
    speed: float | None = Field(default=None, gt=0)
    vars: dict[str, Any] | None = None


class DemoClockBody(_Body):
    """``POST /demo/clock`` (02 §8.8): ``at`` is a Beijing market time (ISO 8601) or epoch ns."""

    target: ClockTarget
    at: str | int | None = None
    at_ns: int | None = None


