"""Regenerate the mock backend's generated data from the Python sources.

    .venv/Scripts/python web/scripts/gen_mock_schema.py      (from the repository root)

Writes
  web/src/mock/wire.gen.ts   msgspec defaults / nesting of every futrisk.messages struct:
                             the api-gateway renders payloads with msgspec.to_builtins and
                             the message structs use omit_defaults=True, so a field equal to
                             its default is left out of the JSON; mock/wire.ts does the same.
  web/src/mock/rules.gen.ts  config/risk_rules.yaml as RiskRulesConfig.model_dump(mode="json")
                             (every default filled in), i.e. what GET /risk/rules returns.
"""

from __future__ import annotations

import enum
import importlib
import inspect
import json
import pkgutil
from pathlib import Path

import msgspec
import msgspec.inspect as mi
import yaml

import futrisk.messages as messages
from futrisk.common.config.risk_rules import RiskRulesConfig

ROOT = Path(__file__).resolve().parents[2]
MOCK = ROOT / "web" / "src" / "mock"


def _jsonable(v: object) -> object:
    if isinstance(v, enum.Enum):
        return v.value
    return msgspec.to_builtins(v)


def _nested(t: object) -> str | None:
    if isinstance(t, mi.StructType):
        return t.cls.__name__
    if isinstance(t, (mi.ListType, mi.SetType, mi.FrozenSetType, mi.VarTupleType)):
        return _nested(t.item_type)
    if isinstance(t, mi.DictType):
        inner = _nested(t.value_type)
        return f"{inner}{{}}" if inner and not inner.endswith("{}") else None
    if isinstance(t, mi.UnionType):
        for x in t.types:
            n = _nested(x)
            if n:
                return n
    return None


def wire_schema() -> dict[str, dict[str, object]]:
    structs: dict[str, type] = {}
    for m in pkgutil.iter_modules(messages.__path__):
        mod = importlib.import_module(f"futrisk.messages.{m.name}")
        for name, cls in vars(mod).items():
            if inspect.isclass(cls) and issubclass(cls, msgspec.Struct) and cls.__module__ == mod.__name__:
                structs[name] = cls
    out: dict[str, dict[str, object]] = {}
    for name, cls in sorted(structs.items()):
        info = mi.type_info(cls)
        omit = bool(cls.__struct_config__.omit_defaults)
        defaults: dict[str, object] = {}
        nested: dict[str, str] = {}
        for f in info.fields:
            if f.default is not msgspec.NODEFAULT:
                defaults[f.encode_name] = _jsonable(f.default)
            elif f.default_factory is not msgspec.NODEFAULT:
                defaults[f.encode_name] = _jsonable(f.default_factory())
            n = _nested(f.type)
            if n:
                nested[f.encode_name] = n
        if (omit and defaults) or nested:
            out[name] = {"omit": omit, "defaults": defaults if omit else {}, "nested": nested}
    return out


def main() -> None:
    body = json.dumps(wire_schema(), ensure_ascii=False, indent=1, sort_keys=True)
    (MOCK / "wire.gen.ts").write_text(
        "/**\n"
        " * GENERATED by web/scripts/gen_mock_schema.py from futrisk.messages (msgspec type info) — do not edit.\n"
        " * Per struct: `omit` = omit_defaults (fields equal to `defaults` are left out of the JSON\n"
        " * the gateway sends), `nested` = field -> struct name (`Name{}` = dict of Name).\n"
        " */\n"
        "export interface WireStruct {\n  omit: boolean\n  defaults: Record<string, unknown>\n  nested: Record<string, string>\n}\n\n"
        f"export const WIRE: Record<string, WireStruct> = {body}\n",
        encoding="utf-8",
        newline="\n",
    )
    raw = yaml.safe_load((ROOT / "config" / "risk_rules.yaml").read_text(encoding="utf-8"))
    rules = [r.model_dump(mode="json") for r in RiskRulesConfig.model_validate(raw).rules]
    (MOCK / "rules.gen.ts").write_text(
        "/**\n"
        " * GENERATED from config/risk_rules.yaml (RiskRulesConfig, `model_dump(mode=\"json\")` with every\n"
        " * default filled in) — the same objects GET /risk/rules returns in `rules`. Do not edit by hand;\n"
        " * regenerate with web/scripts/gen_mock_schema.py when the config changes.\n"
        " */\n"
        "import type { RuleDef } from '@/types'\n\n"
        f"export const RULES: RuleDef[] = {json.dumps(rules, ensure_ascii=False, indent=2)}\n",
        encoding="utf-8",
        newline="\n",
    )
    print("wrote", MOCK / "wire.gen.ts", "and", MOCK / "rules.gen.ts")


if __name__ == "__main__":
    main()
